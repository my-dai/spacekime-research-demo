#!/usr/bin/env python3
"""Validate analytic Laplace kimesurfaces and optionally compare official TCIU R."""

from __future__ import annotations

import argparse
import csv
import json
import shutil
from pathlib import Path

import numpy as np

from spacekime_analytic import (
    ANALYTIC_REPRESENTATION,
    TCIU_CONFORMANCE_ABS_TOL,
    compare_tciu_reference,
    inverse_laplace_bromwich,
    run_closed_form_conformance,
)
from spacekime_paths import PROJECT_ROOT


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--tciu-reference",
        type=Path,
        help="CSV generated by tools/generate_tciu_reference.R",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=PROJECT_ROOT / "output" / "tciu_conformance",
    )
    parser.add_argument(
        "--tciu-abs-tol",
        type=float,
        default=TCIU_CONFORMANCE_ABS_TOL,
        help="Maximum accepted absolute error against every official TCIU::LT case",
    )
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    rows = run_closed_form_conformance()
    csv_path = args.output_dir / "analytic_lt_conformance.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    errors = np.asarray([float(row["absolute_error"]) for row in rows])

    inverse_time = np.linspace(0.15, 2.0, 30)
    inverse_exp = inverse_laplace_bromwich(
        lambda z: 1.0 / (z + 0.7), inverse_time
    )
    inverse_reference = np.exp(-0.7 * inverse_time)
    inverse_rmse = float(np.sqrt(np.mean((inverse_exp - inverse_reference) ** 2)))

    r_reference = None
    if args.tciu_reference is not None:
        r_reference = compare_tciu_reference(
            args.tciu_reference,
            absolute_tolerance=args.tciu_abs_tol,
        )
    manifest = {
        "representation": ANALYTIC_REPRESENTATION,
        "closed_form_conformance": {
            "cases": len(rows),
            "max_absolute_error": float(np.max(errors)),
            "mean_absolute_error": float(np.mean(errors)),
            "passed_at_1e-7": bool(np.max(errors) < 1e-7),
        },
        "inverse_bromwich_baseline": {
            "function": "exp(-0.7 t)",
            "time_min": float(inverse_time.min()),
            "time_max": float(inverse_time.max()),
            "rmse": inverse_rmse,
            "claimed_equivalent_to_tciu_ilt": False,
        },
        "official_r_conformance": r_reference,
        "official_r_executed": False,
        "official_r_reference_compared": r_reference is not None,
        "reference_provenance_note": "This Python runner compares a supplied CSV; it does not execute R. See the separate R-generation or CI log for execution provenance.",
        "rscript_available_in_this_environment": shutil.which("Rscript") is not None,
        "scientific_boundary": {
            "analytic_laplace_surface": "F(x+i y), deterministic transform of a function",
            "synthetic_latent_surface": "known repeated-measurement H(t,theta)",
            "real_fmri": "observed complex-signal spatial phase-distribution proxy",
        },
    }
    manifest_path = args.output_dir / "tciu_conformance_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    summary_path = args.output_dir / "tciu_conformance_summary.txt"
    official_summary = "Official TCIU R reference compared: False"
    if r_reference is not None:
        official_summary = (
            "Official TCIU R conformance: "
            f"{r_reference['max_absolute_error']:.3e} max error <= "
            f"{r_reference['absolute_tolerance']:.3e}: "
            f"{r_reference['passed_at_tolerance']}"
        )
    summary_path.write_text(
        "\n".join(
            [
                "# Analytic Laplace / TCIU conformance",
                "",
                f"Closed-form cases: {len(rows)}",
                f"Maximum forward-LT absolute error: {np.max(errors):.3e}",
                f"Bromwich inverse baseline RMSE: {inverse_rmse:.6f}",
                official_summary,
                "R executed by this Python runner: False (CSV comparison only)",
                f"Rscript available here: {shutil.which('Rscript') is not None}",
                "",
                "The analytic Laplace surface, synthetic latent repeated-measurement surface,",
                "and real-fMRI observed phase proxy are distinct scientific objects.",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    print(json.dumps(manifest, indent=2))
    print(f"Wrote: {csv_path.resolve()}")
    print(f"Wrote: {manifest_path.resolve()}")
    print(f"Wrote: {summary_path.resolve()}")
    analytic_passed = manifest["closed_form_conformance"]["passed_at_1e-7"]
    official_passed = r_reference is None or r_reference["passed_at_tolerance"]
    return 0 if analytic_passed and official_passed else 2


if __name__ == "__main__":
    raise SystemExit(main())
